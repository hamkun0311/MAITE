import { test, expect } from "@playwright/test";
import sharp from "sharp";
import { generateCharacter, enterCharacterMode, chapterEvent, storyWire } from "./character-helpers";

const jpeg = () => sharp({ create: { width: 72, height: 128, channels: 3, background: "#b9d4db" } }).jpeg().toBuffer();

test("outfit button requires clothing in the latest completed exchange and persists its disabled state", async ({ page }) => {
  await page.goto("/ideal");
  await generateCharacter(page);
  let count = 0;
  await page.route("**/api/chat", route => {
    count++;
    if (count === 3) return route.fulfill({ contentType: "text/event-stream", body: 'data: {"type":"clothing","mentioned":true}\n\ndata: {"type":"error","message":"응답이 중단되었습니다."}\n\n' });
    if (count === 4) return route.fulfill({ contentType: "text/event-stream", body: 'data: {"type":"delta","text":"이번에는 유카타로 정했어."}\n\ndata: {"type":"done"}\n\n' });
    const text = count === 1 ? "키톤으로 정했어." : "고마워. 같이 가자.";
    return route.fulfill({ contentType: "text/event-stream", body: `data: ${JSON.stringify({ type: "delta", text })}\n\ndata: ${JSON.stringify({ type: "clothing", mentioned: count === 1 })}\n\ndata: {"type":"done"}\n\n` });
  });
  let imageRequests = 0;
  await page.route("**/api/characters", route => { imageRequests++; return route.abort(); });
  await enterCharacterMode(page);
  const chat = page.getByRole("region", { name: "대화하기", exact: true });
  const button = chat.getByRole("button", { name: "의상 변경하기", exact: true });
  await expect(button).toHaveCount(0);
  const send = async (text: string) => {
    await chat.getByLabel("AI에게 보낼 메시지").fill(text);
    await chat.getByRole("button", { name: "AI 메시지 보내기" }).click();
    await expect(chat.getByLabel("AI에게 보낼 메시지")).toBeEnabled();
  };
  await send("어떤 걸로 정했어?");
  await expect(button).toBeEnabled();
  await send("알았어");
  await expect(button).toBeDisabled();
  await button.evaluate(element => (element as HTMLButtonElement).click());
  expect(imageRequests).toBe(0);
  await page.goBack();
  await expect(page.getByRole("group", { name: "캐릭터와 함께하기" })).toBeVisible();
  await enterCharacterMode(page);
  await expect(button).toBeDisabled();
  await send("다음 장면");
  await expect(chat.getByText("응답이 중단되었습니다.")).toBeVisible();
  await expect(button).toBeDisabled();
  await send("다른 건 어때?");
  await expect(button).toBeEnabled();
  await chat.getByRole("button", { name: "AI 대화 초기화", exact: true }).click();
  await expect(button).toHaveCount(0);
});

test("plain dialogue, outfit images, story illustrations and shared background choices stay connected", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/ideal");
  await generateCharacter(page);
  const originalUrl = await page.getByAltText("은발 탐정 — 생성된 2D 캐릭터 일러스트").getAttribute("src");
  const imageBodies: { kind: string; context: string }[] = [];
  const image = await jpeg();
  await page.route("**/api/characters", async route => {
    const form = await new Request(route.request().url(), { method: "POST", headers: route.request().headers(), body: new Uint8Array(route.request().postDataBuffer()!) }).formData();
    const scene = JSON.parse(String(form.get("scene")));
    imageBodies.push(scene);
    const message = JSON.parse(String(form.get("messages")))[0].content;
    expect(message).toContain(scene.kind === "outfit" ? "현재 실제 장소" : "실제 현재 장소");
    if (scene.kind === "illustration") expect(message).toContain("원본 배경·과거 장면·회상");
    expect((form.get("image") as File).name).toBe("original-character.jpg");
    expect(JSON.parse(String(form.get("profile"))).name).toBe("서하");
    expect(scene.context).not.toContain("**");
    await route.fulfill({ contentType: "image/jpeg", headers: { "X-Character-Title": encodeURIComponent(scene.kind === "outfit" ? "유카타의 서하" : "카페에서의 대화") }, body: image });
  });
  const latestStory = "창가에서\n\n유카타를 입은 서하는 커피잔을 내려놓고 작업실에서 있었던 사건을 떠올렸다. 내일은 서점에서 친구를 만나기로 했다.";
  const storyChapter = chapterEvent({}, latestStory);
  storyChapter.state.summary = "서하는 작업실을 떠나 카페에 도착했다.";
  storyChapter.state.currentSituation = "서하는 카페 창가 테이블에 앉아 대화하고 있다.";
  await page.evaluate(storyChapter => {
    const original = window.fetch.bind(window);
    const scope = window as typeof window & { finishVisualChat?: () => void; revokedImageUrls?: string[] };
    scope.revokedImageUrls = [];
    const revoke = URL.revokeObjectURL.bind(URL);
    URL.revokeObjectURL = url => { scope.revokedImageUrls!.push(url); revoke(url); };
    let calls = 0;
    window.fetch = async (input, init) => {
      if (input !== "/api/chat") return original(input, init);
      calls++;
      const encoder = new TextEncoder();
      return new Response(new ReadableStream({ start(controller) {
        const finish = (text: string) => { controller.enqueue(encoder.encode(`data: ${JSON.stringify({ type: "delta", text })}\n\ndata: {"type":"done"}\n\n`)); controller.close(); };
        if (calls === 1) scope.finishVisualChat = () => finish("백화점 피팅룸에서 **유카타**로 갈아입었어. 어때? 😊 ^_^~");
        else {
          controller.enqueue(encoder.encode(`data: ${JSON.stringify(storyChapter)}\n\ndata: {"type":"done"}\n\n`));
          controller.close();
        }
      } }), { headers: { "Content-Type": "text/event-stream" } });
    };
  }, storyChapter);
  await enterCharacterMode(page);
  const chat = page.getByRole("region", { name: "대화하기", exact: true });
  await expect(chat.getByRole("button", { name: "의상 변경하기", exact: true })).toHaveCount(0);
  await chat.getByLabel("AI에게 보낼 메시지").fill("작업실을 나와 백화점 의류 매장에 도착했어. 여기서 유카타를 입어줘.");
  await chat.getByRole("button", { name: "AI 메시지 보내기" }).click();
  await expect(chat.getByRole("log").getByText("대화 작성중", { exact: true })).toBeVisible();
  await page.evaluate(() => (window as typeof window & { finishVisualChat?: () => void }).finishVisualChat!());
  await expect(chat.locator(".assistant p")).toHaveText("백화점 피팅룸에서 유카타로 갈아입었어. 어때? 😊 ^_^~");
  await chat.getByRole("button", { name: "의상 변경하기", exact: true }).click();
  const viewer = page.getByRole("dialog", { name: "캐릭터 이미지 전체화면", exact: true });
  await expect(viewer.getByAltText("유카타의 서하 — 전체화면 이미지")).toBeVisible();
  const outfitUrl = await chat.locator(".character-backdrop").getAttribute("src");
  expect(outfitUrl).not.toBe(originalUrl);
  expect(imageBodies[0]).toMatchObject({ kind: "outfit" });
  expect(imageBodies[0].context).toContain("유카타");
  expect(imageBodies[0].context).toContain("백화점 피팅룸");
  expect(imageBodies[0].context).not.toContain("미소를 짓는다");
  await viewer.getByRole("button", { name: "전체화면 닫기" }).click();
  await chat.getByRole("button", { name: "배경 변경", exact: true }).click();
  let picker = page.getByRole("dialog", { name: "배경 변경", exact: true });
  await expect(picker.locator(".background-picker-grid > button")).toHaveCount(2);
  await picker.getByRole("button", { name: "배경 선택: 은발 탐정", exact: true }).click();
  await expect(chat.locator(".character-backdrop")).toHaveAttribute("src", originalUrl!);
  await enterCharacterMode(page, "이야기 만들기");
  const story = page.getByRole("region", { name: "이야기 만들기", exact: true });
  await expect(story.locator(".assistant p")).toHaveText(latestStory);
  const illustration = story.getByRole("button", { name: "삽화 생성", exact: true });
  const next = story.getByRole("button", { name: "다음 이야기", exact: true });
  expect((await illustration.boundingBox())!.y).toBeLessThan((await next.boundingBox())!.y);
  await illustration.click();
  await expect(viewer.getByAltText("카페에서의 대화 — 전체화면 이미지")).toBeVisible();
  const storyUrl = await story.locator(".character-backdrop").getAttribute("src");
  expect(imageBodies[1].kind).toBe("illustration");
  expect(imageBodies[1].context).toContain("Current situation after the latest chapter: 서하는 카페 창가");
  expect(imageBodies[1].context).toContain(latestStory);
  await page.keyboard.press("Escape");
  await story.getByRole("button", { name: "배경 변경", exact: true }).click();
  picker = page.getByRole("dialog", { name: "배경 변경", exact: true });
  await expect(picker.locator(".background-picker-grid > button")).toHaveCount(3);
  await picker.getByRole("button", { name: "배경 선택: 유카타의 서하", exact: true }).click();
  await expect(story.locator(".character-backdrop")).toHaveAttribute("src", outfitUrl!);
  await page.screenshot({ path: ".verification/story-illustration-background.png" });
  await enterCharacterMode(page);
  await expect(chat.locator(".character-backdrop")).toHaveAttribute("src", originalUrl!);
  await expect(chat.locator(".assistant p")).toHaveText("백화점 피팅룸에서 유카타로 갈아입었어. 어때? 😊 ^_^~");
  await page.getByRole("button", { name: "새 캐릭터 대화" }).click();
  await expect(page).toHaveURL(/\/ideal$/);
  await expect(page.locator(".character-backdrop")).toHaveCount(0);
  const revoked = await page.evaluate(() => (window as typeof window & { revokedImageUrls: string[] }).revokedImageUrls);
  expect(revoked).toContain(outfitUrl);
  expect(revoked).toContain(storyUrl);
});

test("cancelled and failed illustrations preserve the gallery and a late response cannot revive a reset character", async ({ page }) => {
  await page.goto("/ideal");
  await generateCharacter(page);
  await page.route("**/api/chat", route => route.fulfill({ contentType: "text/event-stream", body: storyWire(route.request().postDataJSON(), "서하는 서점의 창가에서 유카타의 소매를 정리했다.") }));
  await enterCharacterMode(page, "이야기 만들기");
  const story = page.getByRole("region", { name: "이야기 만들기", exact: true });
  const original = await story.locator(".character-backdrop").getAttribute("src");
  await expect(story.getByRole("button", { name: "삽화 생성", exact: true })).toBeEnabled();
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const image = await jpeg();
  await page.route("**/api/characters", async route => { await gate; await route.fulfill({ contentType: "image/jpeg", body: image }).catch(() => {}); });
  await story.getByRole("button", { name: "삽화 생성", exact: true }).click();
  await expect(story.getByRole("button", { name: "다음 이야기", exact: true })).toBeDisabled();
  await story.getByRole("button", { name: "이미지 생성 취소", exact: true }).click();
  release();
  await expect(story.getByRole("alert")).toContainText("취소했습니다");
  await expect(story.locator(".character-backdrop")).toHaveAttribute("src", original!);
  await page.unroute("**/api/characters");
  await page.route("**/api/characters", route => route.fulfill({ status: 503, json: { error: "이미지 서비스에 연결하지 못했습니다." } }));
  await story.getByRole("button", { name: "삽화 생성", exact: true }).click();
  await expect(story.getByRole("alert")).toHaveText("이미지 서비스에 연결하지 못했습니다.");
  await expect(story.locator(".character-backdrop")).toHaveAttribute("src", original!);
  await story.getByRole("button", { name: "배경 변경", exact: true }).click();
  const picker = page.getByRole("dialog", { name: "배경 변경", exact: true });
  await expect(picker.locator(".background-picker-grid > button")).toHaveCount(1);
  await picker.getByRole("button", { name: "배경 선택 닫기", exact: true }).click();
  await page.unroute("**/api/characters");
  let finish!: () => void;
  const late = new Promise<void>(resolve => { finish = resolve; });
  await page.route("**/api/characters", async route => { await late; await route.fulfill({ contentType: "image/jpeg", headers: { "X-Character-Title": encodeURIComponent("오래된 삽화") }, body: image }).catch(() => {}); });
  await story.getByRole("button", { name: "삽화 생성", exact: true }).click();
  await expect(story.getByRole("button", { name: "이미지 생성 취소", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "새 캐릭터 대화" }).click();
  finish();
  await expect(page).toHaveURL(/\/ideal$/);
  await expect(page.locator(".character-backdrop")).toHaveCount(0);
  await expect(page.getByRole("dialog", { name: "캐릭터 이미지 전체화면", exact: true })).toHaveCount(0);
});
